/**
 * FaceVision — Quick Actions Component
 * 
 * Provides quick access to common actions from anywhere.
 */

import React from 'react';
import { useNavigationStore, QuickAction } from '@/lib/store/AppStore';
import { cn } from '@/lib/utils';

interface QuickActionsProps {
  className?: string;
}

export function QuickActions({ className }: QuickActionsProps) {
  const { quickActions } = useNavigationStore();

  const handleAction = (action: QuickAction) => {
    action.action();
  };

  return (
    <div className={cn("flex items-center gap-2", className)}>
      {quickActions.map((action) => (
        <button
          key={action.id}
          onClick={() => handleAction(action)}
          className="flex items-center gap-2 px-3 py-1.5 text-xs font-mono uppercase tracking-wider
                     border border-primary/50 hover:bg-primary/10 hover:border-primary
                     transition-all duration-200"
          title={action.shortcut ? `${action.label} (${action.shortcut})` : action.label}
        >
          <Icon name={action.icon} className="w-3 h-3" />
          <span>{action.label}</span>
          {action.shortcut && (
            <kbd className="ml-1 px-1 py-0.5 text-[10px] bg-primary/20 rounded">
              {action.shortcut}
            </kbd>
          )}
        </button>
      ))}
    </div>
  );
}

