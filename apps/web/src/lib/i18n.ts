export const useI18n = create<I18nState>((set, get) => ({
  language: 'en',
  setLanguage: (lang) => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    set({ language: lang });
  },
  t: (key) => {
    const lang = get().language;
    return translations[lang][key] || key;
  }
}));
